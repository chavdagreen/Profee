import { jsPDF } from 'jspdf';
import { Invoice, Receipt, BillingSettings } from '../types';

// ─── Color helpers ────────────────────────────────────────────────────────────

type RGB = [number, number, number];

function hexToRgb(hex: string): RGB {
  const r = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  return r ? [parseInt(r[1], 16), parseInt(r[2], 16), parseInt(r[3], 16)] : [79, 70, 229];
}

const fc = (p: jsPDF, c: RGB) => p.setFillColor(c[0], c[1], c[2]);
const tc = (p: jsPDF, c: RGB) => p.setTextColor(c[0], c[1], c[2]);
const dc = (p: jsPDF, c: RGB) => p.setDrawColor(c[0], c[1], c[2]);

const S800: RGB = [30,  41,  59];
const S500: RGB = [100, 116, 139];
const S300: RGB = [203, 213, 225];
const S100: RGB = [241, 245, 249];
const S50:  RGB = [248, 250, 252];
const WHT:  RGB = [255, 255, 255];
const EMR:  RGB = [16,  185, 129];

// ─── Utility ─────────────────────────────────────────────────────────────────

function inr(n: number, decimals = 0): string {
  return 'Rs.' + (n || 0).toLocaleString('en-IN', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
}

function fmtDate(d?: string): string {
  if (!d) return '—';
  return new Date(d).toLocaleDateString('en-IN', {
    day: '2-digit', month: 'short', year: 'numeric',
  }).toUpperCase();
}

function numberToWords(num: number): string {
  const a = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine',
    'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen',
    'Seventeen', 'Eighteen', 'Nineteen'];
  const b = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];
  const fmt = (n: number): string => {
    if (n < 20)  return a[n];
    if (n < 100) return b[Math.floor(n / 10)] + (n % 10 ? ' ' + a[n % 10] : '');
    if (n < 1000)    return a[Math.floor(n / 100)] + ' Hundred' + (n % 100 ? ' And ' + fmt(n % 100) : '');
    if (n < 100000)  return fmt(Math.floor(n / 1000)) + ' Thousand' + (n % 1000 ? ' ' + fmt(n % 1000) : '');
    if (n < 10000000)return fmt(Math.floor(n / 100000)) + ' Lakh' + (n % 100000 ? ' ' + fmt(n % 100000) : '');
    return n.toString();
  };
  return fmt(Math.floor(num)).trim() + ' Rupees Only';
}

async function fetchBase64(url: string): Promise<string | null> {
  try {
    const res = await fetch(url);
    if (!res.ok) return null;
    const blob = await res.blob();
    return new Promise(resolve => {
      const reader = new FileReader();
      reader.onloadend = () => resolve(reader.result as string);
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}

function addFooterWatermark(pdf: jsPDF) {
  const pages = pdf.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    pdf.setPage(i);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(7.5);
    tc(pdf, S300);
    pdf.text('Generated by Profee.in', 14, 291);
    pdf.text(`Page ${i} of ${pages}`, 196, 291, { align: 'right' });
  }
}

// ─── INVOICE PDF ──────────────────────────────────────────────────────────────
// Faithfully reproduces the on-screen InvoiceTemplate design.

export async function generateInvoicePDF(invoice: Invoice, settings: BillingSettings): Promise<void> {
  const pdf  = new jsPDF('p', 'mm', 'a4');
  const W    = 210;
  const M    = 14;       // left/right margin
  const CW   = W - M * 2; // 182 mm usable width
  const THM  = hexToRgb(invoice.themeColor || settings.themeColor || '#4f46e5');

  let y = M;

  // ── 1. HEADER ──────────────────────────────────────────────────────────────
  // "INVOICE" large title
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(36);
  tc(pdf, THM);
  pdf.text('INVOICE', M, y + 13);

  // Practice name + subtitle (top-right)
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(13);
  tc(pdf, S800);
  pdf.text(settings.practiceName.toUpperCase(), W - M, y + 7, { align: 'right' });

  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(8);
  tc(pdf, S500);
  pdf.text('Tax Professionals & Consultants', W - M, y + 13, { align: 'right' });

  y += 21;

  // ── 2. INVOICE META ────────────────────────────────────────────────────────
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(7.5);
  tc(pdf, S500);
  pdf.text('Invoice#', M, y);

  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  tc(pdf, S800);
  pdf.text(invoice.invoiceNumber || '—', M, y + 5.5);

  y += 10;

  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(7.5);
  tc(pdf, S500);
  pdf.text('Date', M, y);
  pdf.text('Due Date', M + 44, y);

  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  tc(pdf, S800);
  pdf.text(fmtDate(invoice.date), M, y + 5.5);
  pdf.text(fmtDate(invoice.dueDate), M + 44, y + 5.5);

  y += 15;

  // ── 3. BILLED BY / BILLED TO ───────────────────────────────────────────────
  const BOX_W = (CW - 5) / 2;
  const BOX_H = 36;

  function drawInfoBox(bx: number, by: number, caption: string, capColor: RGB,
                       name: string, address: string, gstin: string, pan: string) {
    fc(pdf, S50);  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.3);
    pdf.roundedRect(bx, by, BOX_W, BOX_H, 2.5, 2.5, 'FD');

    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);
    tc(pdf, capColor);
    pdf.text(caption, bx + 4, by + 6);

    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(10);
    tc(pdf, S800);
    pdf.text(name.toUpperCase().slice(0, 32), bx + 4, by + 13);

    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7.5);
    tc(pdf, S500);
    const addrLines = pdf.splitTextToSize(address || '', BOX_W - 8);
    addrLines.slice(0, 2).forEach((line: string, i: number) =>
      pdf.text(line, bx + 4, by + 18.5 + i * 4));

    // GSTIN / PAN
    const gy = by + BOX_H - 8;
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);
    tc(pdf, S500);  pdf.text('GSTIN', bx + 4, gy);
    tc(pdf, S800);  pdf.text(' ' + (gstin || 'N/A'), bx + 4 + pdf.getTextWidth('GSTIN'), gy);

    tc(pdf, S500);  pdf.text('PAN', bx + 4, gy + 5);
    tc(pdf, S800);  pdf.text(' ' + (pan || 'N/A'), bx + 4 + pdf.getTextWidth('PAN'), gy + 5);
  }

  drawInfoBox(M,           y, 'Billed By', THM,
    settings.practiceName, settings.address, settings.gstin, settings.pan);
  drawInfoBox(M + BOX_W + 5, y, 'Billed To', S500,
    invoice.clientName, invoice.clientAddress || 'Address details on file',
    invoice.clientGstin || 'URD', invoice.clientPan || 'N/A');

  y += BOX_H + 5;

  // ── 4. PLACE OF SUPPLY BAR ─────────────────────────────────────────────────
  fc(pdf, S50);  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.2);
  pdf.rect(M, y, CW, 7, 'FD');
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);  tc(pdf, S800);
  pdf.text(`Place of Supply: ${invoice.placeOfSupply || '—'}`, M + 4, y + 4.7);
  pdf.text(`Country of Supply: ${invoice.countryOfSupply || 'India'}`, M + CW - 4, y + 4.7, { align: 'right' });

  y += 11;

  // ── 5. ITEMS TABLE ─────────────────────────────────────────────────────────
  const hasGst = settings.isGstApplicable;

  // Column layout — widths sum to CW = 182
  // With GST:    #(8) desc(54) hsn(14) qty(10) gst%(10) taxable(28) sgst(20) cgst(20) amount(18) = 182
  // Without GST: #(8) desc(96) hsn(18) qty(14) amount(46) = 182
  type Align = 'left' | 'center' | 'right';
  type ColDef = { label: string; w: number; align: Align };

  const COLS: ColDef[] = hasGst
    ? [
        { label: 'Item #/Item Description', w: 62, align: 'left'   },
        { label: 'HSN',                      w: 14, align: 'center' },
        { label: 'Qty.',                     w: 10, align: 'center' },
        { label: 'GST',                      w: 10, align: 'center' },
        { label: 'Taxable Amount',            w: 28, align: 'right'  },
        { label: 'SGST',                     w: 19, align: 'right'  },
        { label: 'CGST',                     w: 19, align: 'right'  },
        { label: 'Amount',                   w: 20, align: 'right'  },
      ]
    : [
        { label: 'Item #/Item Description', w: 96, align: 'left'   },
        { label: 'HSN',                      w: 18, align: 'center' },
        { label: 'Qty.',                     w: 14, align: 'center' },
        { label: 'Amount',                   w: 54, align: 'right'  },
      ];

  // Column X positions
  const CX: number[] = [M];
  COLS.forEach((c, i) => { if (i < COLS.length - 1) CX.push(CX[i] + c.w); });

  // Header row
  const HDR_H = 8.5;
  fc(pdf, THM);
  pdf.roundedRect(M, y, CW, HDR_H, 2, 2, 'F');
  // Fill lower half flush (only top-left/top-right rounded on real invoice, approximate with full round)
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);  tc(pdf, WHT);
  COLS.forEach((col, i) => {
    const isLast = i === COLS.length - 1;
    const tx = col.align === 'right'
      ? (isLast ? M + CW : CX[i] + col.w - 2)
      : col.align === 'center'
      ? CX[i] + col.w / 2
      : CX[i] + (i === 0 ? 3 : 2);
    pdf.text(col.label, tx, y + 5.6, { align: col.align });
  });
  y += HDR_H;

  // Item rows
  const items = invoice.items || [];
  items.forEach((item, idx) => {
    const taxable = item.qty * item.rate * (1 - (invoice.discountPercent || 0) / 100);
    const tax     = taxable * (item.gstPercent / 100);
    const rowAmt  = taxable + tax;

    // Description may wrap
    const descAvail = COLS[0].w - 9; // minus space for item number gutter
    const descLines = pdf.splitTextToSize(item.description || '', descAvail);
    const subLines  = item.subNotes ? pdf.splitTextToSize(item.subNotes, descAvail) : [];
    const lineCount = descLines.length + (subLines.length > 0 ? subLines.length + 0.2 : 0);
    const ROW_H     = Math.max(9, lineCount * 4.6 + 3);

    if (y + ROW_H > 273) { pdf.addPage(); y = M; }

    const rowBg: RGB = idx % 2 === 0 ? WHT : [249, 250, 251];
    fc(pdf, rowBg);  pdf.rect(M, y, CW, ROW_H, 'F');
    dc(pdf, S100);  pdf.setLineWidth(0.2);
    pdf.line(M, y + ROW_H, M + CW, y + ROW_H);

    const midY = y + ROW_H / 2 + 1.5;

    // Item number (muted)
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(8);  tc(pdf, S300);
    pdf.text(`${idx + 1}.`, CX[0] + 2, midY);

    // Description (bold) + sub-notes (small)
    const descX = CX[0] + 8;
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(8.5);  tc(pdf, S800);
    descLines.forEach((l: string, li: number) => pdf.text(l, descX, y + 5 + li * 4.6));

    if (subLines.length) {
      pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7);  tc(pdf, S500);
      subLines.forEach((l: string, li: number) =>
        pdf.text(l, descX, y + 5 + descLines.length * 4.6 + 2 + li * 3.5));
    }

    // Remaining cols
    const vals = hasGst
      ? [ item.hsn || '',  String(item.qty),  `${item.gstPercent}%`,
          inr(taxable, 2), inr(tax / 2, 2),    inr(tax / 2, 2),  inr(rowAmt, 2) ]
      : [ item.hsn || '',  String(item.qty),  inr(taxable, 2) ];

    vals.forEach((val, ci) => {
      const colIdx = ci + 1;
      const col = COLS[colIdx];
      const cx  = CX[colIdx];
      const isLast = colIdx === COLS.length - 1;
      const tx  = col.align === 'right'
        ? (isLast ? M + CW : cx + col.w - 2)
        : col.align === 'center'
        ? cx + col.w / 2
        : cx + 2;
      pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);
      tc(pdf, col.align === 'center' ? S500 : S800);
      pdf.text(val, tx, midY, { align: col.align });
    });

    y += ROW_H;
  });

  y += 7;

  // ── 6. BANK DETAILS + TOTALS ───────────────────────────────────────────────
  if (y + 72 > 273) { pdf.addPage(); y = M; }

  const BANK_W = CW * 0.50;   // left half
  const TOT_X  = M + BANK_W + 8;
  const TOT_W  = CW - BANK_W - 8;

  // Bank heading
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(8);  tc(pdf, THM);
  pdf.text('Bank & Payment Details', M, y);

  const bankStartY = y + 5;
  const bankFields: [string, string][] = [
    ['ACCOUNT HOLDER NAME', settings.bankDetails.accountHolder || '—'],
    ['ACCOUNT NUMBER',       settings.bankDetails.accountNumber || '—'],
    ['IFSC',                 settings.bankDetails.ifsc          || '—'],
    ['ACCOUNT TYPE',         settings.bankDetails.accountType   || '—'],
    ['BANK',                 settings.bankDetails.bankName      || '—'],
    ['UPI',                  settings.bankDetails.upiId         || '—'],
  ];

  // Two-column bank field grid
  const QR_SIZE   = 22;
  const fieldAreaW = BANK_W - QR_SIZE - 6; // leave room for QR on the right
  const halfFW    = fieldAreaW / 2;

  bankFields.forEach(([label, val], bi) => {
    const col = bi % 2;
    const row = Math.floor(bi / 2);
    const fx  = M + col * (halfFW + 2);
    const fy  = bankStartY + row * 9;

    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(6.5);  tc(pdf, S300);
    pdf.text(label, fx, fy);
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(8);    tc(pdf, S500);
    pdf.text(val, fx, fy + 4.5);
  });

  // QR code image
  const upiId = settings.bankDetails.upiId;
  if (upiId) {
    const qrUrl = `https://api.qrserver.com/v1/create-qr-code/?size=150x150&data=${encodeURIComponent(
      `upi://pay?pa=${encodeURIComponent(upiId)}&pn=${encodeURIComponent(settings.practiceName)}&cu=INR`
    )}`;
    const qrBase64 = await fetchBase64(qrUrl);
    if (qrBase64) {
      const qrX = M + BANK_W - QR_SIZE - 2;
      const qrY = bankStartY - 1;
      pdf.setFont('helvetica', 'bold');  pdf.setFontSize(5.5);  tc(pdf, S500);
      pdf.text('UPI – SCAN TO PAY', qrX + QR_SIZE / 2, qrY - 0.5, { align: 'center' });
      pdf.addImage(qrBase64, 'PNG', qrX, qrY, QR_SIZE, QR_SIZE);
    }
  }

  // Totals (right column)
  let ty = y;
  const totRows: [string, string, boolean][] = [
    ['Sub Total',              inr(invoice.subTotal    || 0), false],
    [`Discount (${invoice.discountPercent || 0}%)`, `- ${inr(invoice.discountAmount || 0)}`, true],
    ['Taxable Amount',         inr(invoice.taxableAmount || 0), false],
    ['CGST',                   inr(invoice.cgstTotal   || 0), false],
    ['SGST',                   inr(invoice.sgstTotal   || 0), false],
  ];

  const RIGHT = M + CW; // true right margin anchor (196mm)
  totRows.forEach(([label, val, isDiscount]) => {
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(9);
    tc(pdf, S500);  pdf.text(label, TOT_X, ty);
    tc(pdf, isDiscount ? EMR : S800);
    pdf.text(val, RIGHT, ty, { align: 'right' });
    ty += 7;
  });

  // Grand total
  dc(pdf, THM);  pdf.setLineWidth(1.2);
  pdf.line(TOT_X, ty, RIGHT, ty);
  ty += 4;

  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(13);  tc(pdf, S800);
  pdf.text('Total', TOT_X, ty + 7);
  pdf.setFontSize(16);
  pdf.text(inr(invoice.total || 0), M + CW, ty + 7, { align: 'right' });
  ty += 13;

  // Amount in words
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(6.5);  tc(pdf, S300);
  pdf.text('INVOICE TOTAL (IN WORDS)', TOT_X, ty);
  ty += 4;

  pdf.setFont('helvetica', 'bolditalic');  pdf.setFontSize(8.5);  tc(pdf, THM);
  const wLines = pdf.splitTextToSize(numberToWords(invoice.total || 0).toUpperCase(), TOT_W);
  wLines.forEach((l: string, i: number) => pdf.text(l, TOT_X, ty + i * 4.5));

  // ── 7. TERMS & CONDITIONS ──────────────────────────────────────────────────
  const bankRowH   = Math.ceil(bankFields.length / 2) * 9;
  const termsY     = bankStartY + bankRowH + 6;

  if (termsY < 270) {
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(8);  tc(pdf, S500);
    pdf.text('Terms & Conditions', M, termsY);

    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7.5);  tc(pdf, S500);
    (settings.terms || []).forEach((term, i) => {
      const lines = pdf.splitTextToSize(`${i + 1}. ${term}`, BANK_W);
      lines.forEach((l: string, li: number) => {
        const lineY = termsY + 5 + i * 8 + li * 4;
        if (lineY < 270) pdf.text(l, M, lineY);
      });
    });
  }

  // Track the lower boundary
  y = Math.max(
    bankStartY + bankRowH + (settings.terms?.length || 0) * 8 + 12,
    ty + wLines.length * 4.5 + 10,
  );

  // ── 8. FOOTER ──────────────────────────────────────────────────────────────
  if (y + 26 > 277) { pdf.addPage(); y = M; }

  dc(pdf, S100);  pdf.setLineWidth(0.4);
  pdf.line(M, y, M + CW, y);
  y += 5;

  // Additional notes (left)
  pdf.setFont('helvetica', 'bold');    pdf.setFontSize(7.5);  tc(pdf, S500);
  pdf.text('Additional Notes', M, y);
  y += 4;
  pdf.setFont('helvetica', 'italic'); pdf.setFontSize(7.5);  tc(pdf, S500);
  const noteLines = pdf.splitTextToSize(invoice.notes || 'Professional services rendered.', CW * 0.5);
  noteLines.slice(0, 3).forEach((l: string, i: number) => pdf.text(l, M, y + i * 4));

  // Right footer note
  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7.5);  tc(pdf, S500);
  pdf.text(
    `For any enquiries, email us on `,
    M + CW, y, { align: 'right' }
  );
  pdf.setFont('helvetica', 'bold');  tc(pdf, S800);
  pdf.text(settings.practiceName, M + CW, y + 4, { align: 'right' });

  // Authorized signatory
  const sigLineY = y + 20;
  if (sigLineY < 282) {
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);  tc(pdf, S300);
    pdf.text('AUTHORIZED SIGNATORY', M + CW, sigLineY - 8, { align: 'right' });

    dc(pdf, S300);  pdf.setLineWidth(0.4);
    pdf.line(M + CW - 48, sigLineY, M + CW, sigLineY);

    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(9);  tc(pdf, S800);
    pdf.text(settings.practiceName, M + CW, sigLineY + 5, { align: 'right' });
  }

  addFooterWatermark(pdf);
  pdf.save(`${invoice.invoiceNumber || 'Invoice'}.pdf`);
}

// ─── RECEIPT PDF ──────────────────────────────────────────────────────────────

export async function generateReceiptPDF(receipt: Receipt, settings: BillingSettings): Promise<void> {
  const pdf = new jsPDF('p', 'mm', 'a4');
  const W   = 210;
  const M   = 14;
  const CW  = W - M * 2;   // 182 mm
  const GRN: RGB = [5, 150, 105];
  const LGN: RGB = [209, 250, 229];

  // ── 1. Header bar (52 mm, all text safely inside) ──────────────────────────
  const HDR_H = 52;
  fc(pdf, GRN);  pdf.rect(0, 0, W, HDR_H, 'F');

  // Left: title + subtitle
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(24);  tc(pdf, WHT);
  pdf.text('PAYMENT RECEIPT', M, 20);

  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(8.5);  tc(pdf, LGN);
  pdf.text('Official Confirmation of Payment', M, 29);

  // Right: practice name, receipt#, date
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(11);  tc(pdf, WHT);
  pdf.text(settings.practiceName.toUpperCase(), W - M, 16, { align: 'right' });

  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(8);  tc(pdf, LGN);
  pdf.text(`Receipt No: ${receipt.receiptNumber}`, W - M, 24, { align: 'right' });
  pdf.text(`Date: ${fmtDate(receipt.date)}`, W - M, 32, { align: 'right' });

  // Practice address (small, bottom of header)
  if (settings.address) {
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7);  tc(pdf, LGN);
    pdf.text(settings.address, W - M, 40, { align: 'right' });
  }

  let y = HDR_H + 10;

  // ── 2. Info box ─────────────────────────────────────────────────────────────
  const BOX_H = 52;
  fc(pdf, S50);  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.3);
  pdf.roundedRect(M, y, CW, BOX_H, 3, 3, 'FD');

  const c1 = M + 8;
  const c2 = M + CW / 2 + 4;

  // Row 1: Received From | Payment Date
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7);  tc(pdf, S300);
  pdf.text('RECEIVED FROM', c1, y + 9);
  pdf.text('PAYMENT DATE', c2, y + 9);

  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(13);  tc(pdf, S800);
  const cName = (receipt.clientName || '—').slice(0, 28);
  pdf.text(cName, c1, y + 18);
  pdf.setFontSize(12);
  pdf.text(fmtDate(receipt.date), c2, y + 18);

  // Horizontal divider
  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.25);
  pdf.line(M + 5, y + 24, M + CW - 5, y + 24);

  // Row 2: Mode of Payment | Transaction Ref
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7);  tc(pdf, S300);
  pdf.text('MODE OF PAYMENT', c1, y + 32);
  pdf.text('TRANSACTION REF.', c2, y + 32);

  // Badge for payment mode
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(8.5);
  const modeText = receipt.paymentMethod || '—';
  const modeW = pdf.getTextWidth(modeText) + 10;
  fc(pdf, WHT);  dc(pdf, [203, 213, 225]);  pdf.setLineWidth(0.4);
  pdf.roundedRect(c1 - 1, y + 35, modeW, 8, 2, 2, 'FD');
  tc(pdf, S800);  pdf.text(modeText, c1 + 4, y + 40.5);

  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(9);  tc(pdf, S800);
  pdf.text(receipt.reference || 'SYSTEM RECORD', c2, y + 41);

  y += BOX_H + 10;

  // ── 3. Amount block ─────────────────────────────────────────────────────────
  const AMT_H = 30;
  fc(pdf, GRN);  pdf.roundedRect(M, y, CW, AMT_H, 3, 3, 'F');

  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);  tc(pdf, LGN);
  pdf.text('AMOUNT RECEIVED', M + 8, y + 9);

  // "Rs." label + number rendered separately to avoid symbol corruption
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(9);  tc(pdf, LGN);
  pdf.text('Rs.', M + 8, y + 23);
  const rsW = pdf.getTextWidth('Rs.');
  pdf.setFontSize(20);  tc(pdf, WHT);
  pdf.text((receipt.amount || 0).toLocaleString('en-IN'), M + 8 + rsW + 1, y + 23);

  y += AMT_H + 10;

  // ── 4. Amount in words + Authorized Signatory (side-by-side, same baseline) ─
  const halfW = CW / 2 - 4;
  const sigColX = M + CW / 2 + 4;

  // Section labels at same Y
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7);  tc(pdf, S300);
  pdf.text('AMOUNT IN WORDS', M, y);
  pdf.text('AUTHORIZED SIGNATORY', sigColX, y);

  y += 6;

  // Words text
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(9);  tc(pdf, S800);
  const wordsLines = pdf.splitTextToSize(numberToWords(receipt.amount || 0), halfW);
  wordsLines.forEach((l: string, i: number) => pdf.text(l, M, y + i * 5));

  // Signature line + name (anchored at same y baseline as words block bottom)
  const sigLineY = y + 22;
  dc(pdf, S300);  pdf.setLineWidth(0.4);
  pdf.line(sigColX, sigLineY, M + CW, sigLineY);

  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(9);  tc(pdf, S800);
  pdf.text(settings.practiceName, sigColX, sigLineY + 5);

  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7.5);  tc(pdf, S500);
  pdf.text('Tax Professional & Consultant', sigColX, sigLineY + 10);

  y += 38;

  // ── 5. Practice details bar ─────────────────────────────────────────────────
  if (y + 18 < 260) {
    fc(pdf, S50);  pdf.roundedRect(M, y, CW, 14, 2, 2, 'F');
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7.5);  tc(pdf, S500);
    const detailParts: string[] = [settings.practiceName];
    if (settings.gstin) detailParts.push(`GSTIN: ${settings.gstin}`);
    if (settings.pan)   detailParts.push(`PAN: ${settings.pan}`);
    pdf.text(detailParts.join('   |   '), W / 2, y + 6, { align: 'center' });
    if (settings.address) {
      pdf.text(settings.address, W / 2, y + 11, { align: 'center' });
    }
    y += 22;
  }

  // ── 6. Footer note ──────────────────────────────────────────────────────────
  dc(pdf, S100);  pdf.setLineWidth(0.25);  pdf.line(M, y, M + CW, y);
  y += 5;
  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7.5);  tc(pdf, S500);
  pdf.text(
    'This is a computer-generated receipt and is valid without a physical signature.',
    W / 2, y, { align: 'center' }
  );

  addFooterWatermark(pdf);
  pdf.save(`${receipt.receiptNumber || 'Receipt'}.pdf`);
}

// ─── CLIENT LEDGER PDF ────────────────────────────────────────────────────────

interface LedgerEntry {
  date: string;
  ref: string;
  description: string;
  type: 'invoice' | 'receipt';
  amount: number;
  balance: number;
}

export function generateClientLedgerPDF(
  clientName: string,
  clientPan: string | undefined,
  entries: LedgerEntry[],
  totalInvoiced: number,
  totalReceived: number,
  practiceName: string,
  dateFrom?: string,
  dateTo?: string,
): void {
  const pdf  = new jsPDF('p', 'mm', 'a4');
  const W    = 210;
  const M    = 14;
  const CW   = W - M * 2;   // 182 mm
  const ROSE: RGB = [220, 38,  72];
  const GREE: RGB = [5,   150, 105];
  const IDIG: RGB = [99,  102, 241];
  type Align = 'left' | 'center' | 'right';

  // ── Header ──────────────────────────────────────────────────────────────────
  fc(pdf, IDIG);  pdf.rect(0, 0, W, 2, 'F');

  let y = 12;
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(20);  tc(pdf, S800);
  pdf.text('CLIENT LEDGER', M, y);

  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(10);  tc(pdf, S800);
  pdf.text(practiceName, W - M, y, { align: 'right' });
  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(8);  tc(pdf, S500);
  pdf.text(`Generated: ${new Date().toLocaleDateString('en-IN')}`, W - M, y + 7, { align: 'right' });

  y += 11;
  dc(pdf, S100);  pdf.setLineWidth(0.4);  pdf.line(M, y, M + CW, y);
  y += 6;

  // ── Client info card ────────────────────────────────────────────────────────
  fc(pdf, S50);  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.3);
  pdf.roundedRect(M, y, CW, 18, 2, 2, 'FD');

  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(12);  tc(pdf, S800);
  pdf.text(clientName.toUpperCase(), M + 5, y + 8);

  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(8);  tc(pdf, S500);
  const infoParts: string[] = [];
  if (clientPan) infoParts.push(`PAN: ${clientPan}`);
  if (dateFrom || dateTo) infoParts.push(`Period: ${dateFrom || 'Start'} to ${dateTo || 'Present'}`);
  if (infoParts.length) pdf.text(infoParts.join('   |   '), M + 5, y + 14);

  // Summary mini-stats inside card (right side)
  const statX = M + CW - 3;
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7);  tc(pdf, S300);
  pdf.text('INVOICED', statX - 88, y + 6, { align: 'right' });
  pdf.text('RECEIVED', statX - 44, y + 6, { align: 'right' });
  pdf.text('OUTSTANDING', statX, y + 6, { align: 'right' });
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(9);
  tc(pdf, ROSE);  pdf.text(inr(totalInvoiced, 2), statX - 88, y + 13, { align: 'right' });
  tc(pdf, GREE);  pdf.text(inr(totalReceived, 2), statX - 44, y + 13, { align: 'right' });
  const outstanding = totalInvoiced - totalReceived;
  tc(pdf, outstanding >= 0 ? ROSE : GREE);
  pdf.text(inr(Math.abs(outstanding), 2) + (outstanding > 0 ? ' Dr' : outstanding < 0 ? ' Cr' : ''), statX, y + 13, { align: 'right' });

  y += 24;

  // ── Table ────────────────────────────────────────────────────────────────────
  // Sr.#(8) Date(22) Invoice#(28) Receipt#(28) Debit(30) Credit(30) Balance(36) = 182
  const colW   = [8, 22, 28, 28, 30, 30, 36];
  const colX: number[] = [M];
  colW.slice(0, -1).forEach((w, i) => colX.push(colX[i] + w));
  const RIGHT  = M + CW;

  const ROW_H  = 9;
  const HDR_H  = 8;
  const SUB_H  = 5;
  const tableH = HDR_H + SUB_H + entries.length * ROW_H + ROW_H + 2;
  fc(pdf, WHT);  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.4);
  pdf.roundedRect(M, y, CW, Math.min(tableH, 260 - y), 3, 3, 'FD');

  // Header row
  fc(pdf, S800);  pdf.roundedRect(M, y, CW, HDR_H, 3, 3, 'F');
  pdf.rect(M, y + HDR_H / 2, CW, HDR_H / 2, 'F');
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7);  tc(pdf, WHT);
  pdf.text('#',           colX[0] + colW[0] / 2, y + 5.5, { align: 'center' });
  pdf.text('Date',        colX[1] + 2,            y + 5.5);
  pdf.text('Invoice #',   colX[2] + 2,            y + 5.5);
  pdf.text('Receipt #',   colX[3] + 2,            y + 5.5);
  pdf.text('Debit',       colX[4] + colW[4] - 2,  y + 5.5, { align: 'right' });
  pdf.text('Credit',      colX[5] + colW[5] - 2,  y + 5.5, { align: 'right' });
  pdf.text('Balance',     RIGHT - 2,               y + 5.5, { align: 'right' });
  y += HDR_H;

  // Sub-label row
  fc(pdf, [241, 245, 249]);  pdf.rect(M, y, CW, SUB_H, 'F');
  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(5.5);  tc(pdf, S500);
  pdf.text('(Amount in Rs.)', colX[4] + colW[4] - 2, y + 3.5, { align: 'right' });
  pdf.text('(Amount in Rs.)', colX[5] + colW[5] - 2, y + 3.5, { align: 'right' });
  pdf.text('Dr = Outstanding', RIGHT - 2, y + 3.5, { align: 'right' });
  y += SUB_H;

  // Data rows
  entries.forEach((entry, idx) => {
    if (y + ROW_H > 275) { pdf.addPage(); y = M; }

    const rowBg: RGB = idx % 2 === 0 ? WHT : [248, 250, 252];
    fc(pdf, rowBg);  pdf.rect(M, y, CW, ROW_H, 'F');
    dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.15);
    pdf.line(M + 2, y + ROW_H, M + CW - 2, y + ROW_H);

    const midY = y + ROW_H / 2 + 1.5;
    const isInv = entry.type === 'invoice';

    // Sr.#
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(6.5);  tc(pdf, S300);
    pdf.text(String(idx + 1), colX[0] + colW[0] / 2, midY, { align: 'center' });

    // Date — single merged column, colored by type
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);
    tc(pdf, isInv ? IDIG : GREE);
    pdf.text(fmtDate(entry.date), colX[1] + 2, midY);

    // Invoice #
    pdf.setFont('helvetica', isInv ? 'bold' : 'normal');
    tc(pdf, isInv ? IDIG : S300);
    pdf.text(isInv ? (entry.ref || '—') : '—', colX[2] + 2, midY);

    // Receipt #
    pdf.setFont('helvetica', !isInv ? 'bold' : 'normal');
    tc(pdf, !isInv ? GREE : S300);
    pdf.text(!isInv ? (entry.ref || '—') : '—', colX[3] + 2, midY);

    // Debit
    if (isInv) {
      pdf.setFont('helvetica', 'bold');  tc(pdf, ROSE);
      pdf.text(inr(entry.amount, 2), colX[4] + colW[4] - 2, midY, { align: 'right' });
    } else {
      pdf.setFont('helvetica', 'normal');  tc(pdf, S300);
      pdf.text('—', colX[4] + colW[4] - 2, midY, { align: 'right' });
    }

    // Credit
    if (!isInv) {
      pdf.setFont('helvetica', 'bold');  tc(pdf, GREE);
      pdf.text(inr(entry.amount, 2), colX[5] + colW[5] - 2, midY, { align: 'right' });
    } else {
      pdf.setFont('helvetica', 'normal');  tc(pdf, S300);
      pdf.text('—', colX[5] + colW[5] - 2, midY, { align: 'right' });
    }

    // Balance
    const balColor: RGB = entry.balance >= 0 ? ROSE : GREE;
    const balTxt = inr(Math.abs(entry.balance), 2) + (entry.balance > 0 ? ' Dr' : entry.balance < 0 ? ' Cr' : '');
    pdf.setFont('helvetica', 'bold');  tc(pdf, balColor);
    pdf.text(balTxt, RIGHT - 2, midY, { align: 'right' });

    y += ROW_H;
  });

  if (!entries.length) {
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(9);  tc(pdf, S500);
    pdf.text('No transactions found for the selected period.', W / 2, y + 8, { align: 'center' });
    y += 16;
  } else {
    // Closing balance row
    if (y + ROW_H > 275) { pdf.addPage(); y = M; }
    fc(pdf, S800);  pdf.roundedRect(M, y, CW, ROW_H, 3, 3, 'F');
    pdf.rect(M, y, CW, ROW_H / 2, 'F');
    const closingBal = entries[entries.length - 1]?.balance ?? 0;
    const closingTxt = inr(Math.abs(closingBal), 2) + (closingBal > 0 ? ' Dr' : closingBal < 0 ? ' Cr' : '');
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);  tc(pdf, WHT);
    pdf.text('CLOSING BALANCE', colX[1] + 2, y + ROW_H / 2 + 1.5);
    pdf.text(closingTxt, RIGHT - 2, y + ROW_H / 2 + 1.5, { align: 'right' });
    y += ROW_H;
  }

  addFooterWatermark(pdf);
  pdf.save(`Ledger_${clientName.replace(/\s+/g, '_')}.pdf`);
}

// ─── GROUP LEDGER PDF ─────────────────────────────────────────────────────────

interface GroupLedgerEntry {
  clientName: string;
  groupName?: string;
  type: 'invoice' | 'receipt';
  date: string;
  ref: string;
  amount: number;
  balance: number;
}

export function generateGroupLedgerPDF(
  entries: GroupLedgerEntry[],
  summaries: { clientName: string; groupName?: string; totalInvoiced: number; totalReceived: number; outstanding: number }[],
  practiceName: string,
  dateFrom?: string,
  dateTo?: string,
  groupTitle?: string,
): void {
  const pdf  = new jsPDF('p', 'mm', 'a4');
  const W    = 210;
  const M    = 14;
  const CW   = W - M * 2;   // 182 mm
  const ROSE: RGB = [220, 38,  38];
  const GREE: RGB = [5,   150, 105];
  const IDIG: RGB = [99,  102, 241]; // indigo accent

  // ── 1. Header ───────────────────────────────────────────────────────────────
  // Thin accent bar at top
  fc(pdf, IDIG);  pdf.rect(0, 0, W, 2, 'F');

  const multiGroup = !groupTitle && summaries.some(s => s.groupName);

  let y = 12;
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(22);  tc(pdf, S800);
  pdf.text(groupTitle ? groupTitle.toUpperCase() : 'GROUP LEDGER', M, y);

  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(10);  tc(pdf, S500);
  pdf.text(groupTitle ? 'Group Ledger Summary' : 'Summary', M, y + 7);

  // Right: practice + period
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(10);  tc(pdf, S800);
  pdf.text(practiceName, W - M, y, { align: 'right' });

  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(8);  tc(pdf, S500);
  const period = dateFrom
    ? `${dateFrom}  to  ${dateTo || 'Present'}`
    : `All time  to  ${dateTo || new Date().toLocaleDateString('en-IN')}`;
  pdf.text(period, W - M, y + 7, { align: 'right' });

  // Thin separator
  y += 13;
  dc(pdf, S100);  pdf.setLineWidth(0.4);  pdf.line(M, y, M + CW, y);
  y += 8;

  // ── 2. Summary stat cards ────────────────────────────────────────────────────
  const grandInv  = summaries.reduce((s, r) => s + r.totalInvoiced, 0);
  const grandRec  = summaries.reduce((s, r) => s + r.totalReceived, 0);
  const grandOut  = grandInv - grandRec;

  const CARD_W = (CW - 8) / 3;
  const CARD_H = 24;
  const cards: [string, string, RGB, RGB][] = [
    ['TOTAL INVOICED',  inr(grandInv, 2), [239, 242, 255], IDIG],
    ['TOTAL RECEIVED',  inr(grandRec, 2), [236, 253, 245], GREE],
    ['OUTSTANDING',     inr(Math.abs(grandOut), 2) + (grandOut > 0 ? '  Dr' : grandOut < 0 ? '  Cr' : ''),
     grandOut > 0 ? [255, 241, 242] : [236, 253, 245],
     grandOut > 0 ? ROSE : GREE],
  ];

  cards.forEach(([label, val, bg, accent], i) => {
    const cx = M + i * (CARD_W + 4);
    fc(pdf, bg as RGB);  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.3);
    pdf.roundedRect(cx, y, CARD_W, CARD_H, 3, 3, 'FD');

    // Left accent bar inside card
    fc(pdf, accent as RGB);  pdf.roundedRect(cx, y, 2.5, CARD_H, 1.5, 1.5, 'F');
    pdf.rect(cx + 1.5, y, 1, CARD_H, 'F'); // flush right side of accent

    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(6.5);  tc(pdf, S500);
    pdf.text(label, cx + 6, y + 7);

    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(11);  tc(pdf, accent as RGB);
    pdf.text(val, cx + 6, y + 18);
  });

  y += CARD_H + 8;

  // ── 3. Detailed transaction table ────────────────────────────────────────────
  // Sr.#(8) Client(46) Date(22) Invoice#(24) Receipt#(24) Debit(22) Credit(22) Balance(14) = 182
  const colW  = [8, 46, 22, 24, 24, 22, 22, 14];
  const colX: number[] = [M];
  colW.slice(0, -1).forEach((w, i) => colX.push(colX[i] + w));
  const RIGHT = M + CW;
  const ROW_H = 9;
  const HDR_H = 8;

  // Table container
  fc(pdf, WHT);  dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.4);
  pdf.roundedRect(M, y, CW, Math.min(HDR_H + 5 + entries.length * ROW_H + ROW_H + 2, 255 - y), 3, 3, 'FD');

  // Header row
  fc(pdf, S800);  pdf.roundedRect(M, y, CW, HDR_H, 3, 3, 'F');
  pdf.rect(M, y + HDR_H / 2, CW, HDR_H / 2, 'F');
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(6.5);  tc(pdf, WHT);
  // Sr.# (center), Client (left), Date (left), Invoice# (left), Receipt# (left),
  // Debit (right), Credit (right), Balance (right)
  pdf.text('#',          colX[0] + colW[0] / 2, y + 5.3, { align: 'center' });
  pdf.text('Client',     colX[1] + 2,            y + 5.3);
  pdf.text('Date',       colX[2] + 2,            y + 5.3);
  pdf.text('Invoice #',  colX[3] + 2,            y + 5.3);
  pdf.text('Receipt #',  colX[4] + 2,            y + 5.3);
  pdf.text('Debit',      colX[5] + colW[5] - 2,  y + 5.3, { align: 'right' });
  pdf.text('Credit',     colX[6] + colW[6] - 2,  y + 5.3, { align: 'right' });
  pdf.text('Balance',    RIGHT - 2,               y + 5.3, { align: 'right' });
  y += HDR_H;

  // Sub-label row
  fc(pdf, [241, 245, 249]);  pdf.rect(M, y, CW, 5, 'F');
  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(5.5);  tc(pdf, S500);
  pdf.text('(Rs.)',  colX[5] + colW[5] - 2, y + 3.5, { align: 'right' });
  pdf.text('(Rs.)',  colX[6] + colW[6] - 2, y + 3.5, { align: 'right' });
  pdf.text('Dr=Due', RIGHT - 2,              y + 3.5, { align: 'right' });
  y += 5;

  // Transaction rows
  entries.forEach((entry, idx) => {
    if (y + ROW_H > 275) { pdf.addPage(); y = M; }

    const rowBg: RGB = idx % 2 === 0 ? WHT : [248, 250, 252];
    fc(pdf, rowBg);  pdf.rect(M, y, CW, ROW_H, 'F');
    dc(pdf, [226, 232, 240]);  pdf.setLineWidth(0.15);
    pdf.line(M + 2, y + ROW_H, M + CW - 2, y + ROW_H);
    const midY = y + ROW_H / 2 + 1.5;
    const isInv = entry.type === 'invoice';

    // Sr. number (muted, centered)
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(6.5);  tc(pdf, S300);
    pdf.text(String(idx + 1), colX[0] + colW[0] / 2, midY, { align: 'center' });

    // Client name — full, no truncation (46mm wide, 7pt fits ~28 chars)
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7);  tc(pdf, S800);
    const maxChars = 26;
    const nm = entry.clientName.length > maxChars
      ? entry.clientName.slice(0, maxChars - 1) + '…'
      : entry.clientName;
    pdf.text(nm, colX[1] + 2, midY);

    // Date — single column, colored by type
    pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7);
    tc(pdf, isInv ? IDIG : GREE);
    pdf.text(fmtDate(entry.date), colX[2] + 2, midY);

    // Invoice # (filled for invoices, — for receipts)
    pdf.setFont('helvetica', isInv ? 'bold' : 'normal');
    tc(pdf, isInv ? IDIG : S300);
    pdf.text(isInv ? (entry.ref || '—') : '—', colX[3] + 2, midY);

    // Receipt # (filled for receipts, — for invoices)
    pdf.setFont('helvetica', !isInv ? 'bold' : 'normal');
    tc(pdf, !isInv ? GREE : S300);
    pdf.text(!isInv ? (entry.ref || '—') : '—', colX[4] + 2, midY);

    // Debit
    if (isInv) {
      pdf.setFont('helvetica', 'bold');  tc(pdf, ROSE);
      pdf.text(inr(entry.amount, 2), colX[5] + colW[5] - 2, midY, { align: 'right' });
    } else {
      pdf.setFont('helvetica', 'normal');  tc(pdf, S300);
      pdf.text('—', colX[5] + colW[5] - 2, midY, { align: 'right' });
    }

    // Credit
    if (!isInv) {
      pdf.setFont('helvetica', 'bold');  tc(pdf, GREE);
      pdf.text(inr(entry.amount, 2), colX[6] + colW[6] - 2, midY, { align: 'right' });
    } else {
      pdf.setFont('helvetica', 'normal');  tc(pdf, S300);
      pdf.text('—', colX[6] + colW[6] - 2, midY, { align: 'right' });
    }

    // Balance
    const balColor: RGB = entry.balance >= 0 ? ROSE : GREE;
    const balTxt = inr(Math.abs(entry.balance), 2) + (entry.balance > 0 ? '\nDr' : entry.balance < 0 ? '\nCr' : '');
    pdf.setFont('helvetica', 'bold');  tc(pdf, balColor);
    // Balance on two lines if needed (amount on top, Dr/Cr tag below)
    const balAmt = inr(Math.abs(entry.balance), 2);
    const balTag = entry.balance > 0 ? 'Dr' : entry.balance < 0 ? 'Cr' : '';
    pdf.setFontSize(6.5);
    pdf.text(balAmt, RIGHT - 2, midY - 1, { align: 'right' });
    if (balTag) {
      pdf.setFontSize(5.5);  tc(pdf, balColor);
      pdf.text(balTag, RIGHT - 2, midY + 3, { align: 'right' });
    }

    y += ROW_H;
  });

  if (entries.length === 0) {
    pdf.setFont('helvetica', 'normal');  pdf.setFontSize(9);  tc(pdf, S500);
    pdf.text('No transactions found.', W / 2, y + 8, { align: 'center' });
    y += 16;
  }

  // Grand total strip
  if (y + ROW_H + 2 > 275) { pdf.addPage(); y = M; }
  y += 1;
  fc(pdf, S800);  pdf.roundedRect(M, y, CW, ROW_H + 1, 3, 3, 'F');
  pdf.rect(M, y, CW, (ROW_H + 1) / 2, 'F');
  const gtY = y + (ROW_H + 1) / 2 + 2;
  pdf.setFont('helvetica', 'bold');  pdf.setFontSize(7.5);  tc(pdf, WHT);
  pdf.text('GRAND TOTAL', colX[1] + 2, gtY);
  pdf.text(inr(grandInv, 2), colX[5] + colW[5] - 2, gtY, { align: 'right' });
  pdf.text(inr(grandRec, 2), colX[6] + colW[6] - 2, gtY, { align: 'right' });
  const outTxt = inr(Math.abs(grandOut), 2) + (grandOut > 0 ? '  Dr' : grandOut < 0 ? '  Cr' : '');
  pdf.text(outTxt, RIGHT - 2, gtY, { align: 'right' });

  y += ROW_H + 10;

  // ── 4. Generated date note ───────────────────────────────────────────────────
  pdf.setFont('helvetica', 'normal');  pdf.setFontSize(7.5);  tc(pdf, S300);
  pdf.text(
    `Generated on ${new Date().toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' })}  |  ${practiceName}`,
    W / 2, y, { align: 'center' }
  );

  addFooterWatermark(pdf);
  pdf.save(`Group_Ledger_${new Date().toISOString().split('T')[0]}.pdf`);
}
